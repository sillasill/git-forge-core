// git.ts — the git object model and wire formats, standard library only.
//
// pkt-line framing, packfile read/write (version 2, plain objects plus OFS/REF
// delta resolution), SHA-1 object ids, tree/commit/tag parse and build. This is
// a from-scratch implementation of the subset the smart-HTTP protocol needs;
// it mirrors the wire shapes the kit's git-client speaks so the two agree
// byte for byte.

import { createHash } from 'node:crypto';
import { deflateSync, inflateSync as zlibInflateSync } from 'node:zlib';

export const ZERO_OID = '0000000000000000000000000000000000000000';

export type GitObjectType = 'commit' | 'tree' | 'blob' | 'tag';

export interface GitObject {
  type: GitObjectType;
  data: Buffer;
}

const HEX40 = /^[0-9a-f]{40}$/;

export function isObjectId(value: string): boolean {
  return HEX40.test(value);
}

/** SHA-1 of `"<type> <size>\0<data>"`. */
export function hashObject(type: GitObjectType, data: Uint8Array): string {
  const header = Buffer.from(`${type} ${data.length}\0`, 'ascii');
  return createHash('sha1').update(header).update(data).digest('hex');
}

// -------------------------------------------------------------------------------------------
// pkt-lines
